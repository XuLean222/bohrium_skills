# ========== 结果解析函数 ==========
def parse_llm_response(response_text: str) -> tuple:
    """
    解析LLM返回的表格结果，提取类别、置信度、关键特征
    返回：(category, confidence, features)，解析失败返回(None, None, None)
    """
    try:
        # 正则匹配表格行
        pattern = r'\|\s*([^|]+?)\s*\|\s*([0-9]\.[0-9])\s*\|\s*([^|]+?)\s*\|'
        matches = re.findall(pattern, response_text)
        
        if matches and len(matches) >= 1:
            category = matches[0][0].strip()
            confidence = matches[0][1].strip()
            features = matches[0][2].strip()
            
            # 验证类别合法性
            valid_categories = ["绝对做不到的", "需要做好但目前的能力做不好的", "必须要做好的", "无效提问类"]
            if category not in valid_categories:
                return (None, None, None)
            
            # 验证置信度格式
            try:
                confidence_float = float(confidence)
                if 0.0 <= confidence_float <= 1.0 and len(confidence.split('.')[-1]) == 1:
                    return (category, confidence, features)
            except:
                pass
        
        return (None, None, None)
    except Exception as e:
        print(f"解析返回结果失败：{str(e)}")
        return (None, None, None)

# ========== LLM调用函数 ==========
def classify_single_query(query: str, max_retries: int = 3) -> tuple:
    """
    调用Azure OpenAI对单个Query进行分类
    参数：
        query: 用户查询文本
        max_retries: 最大重试次数
    返回：(category, confidence, features)
    """
    if not query or str(query).strip() == "":
        return ("无法识别", "0.0", "标题为空；无有效查询内容")
    
    prompt = build_capability_classification_prompt(query.strip())
    
    # 重试机制
    for retry in range(max_retries):
        try:
            # 调用Azure OpenAI
            response = client.chat.completions.create(
                model=DEPLOYMENT_NAME,
                messages=[{"role": "user", "content": prompt}],
                temperature=0,  # 低温度保证结果稳定
                max_completion_tokens=2000
            )
            
            # 解析响应
            response_text = response.choices[0].message.content.strip()
            category, confidence, features = parse_llm_response(response_text)
            
            # 解析成功则返回
            if all([category, confidence, features]):
                return (category, confidence, features)
            
            print(f"第{retry+1}次解析失败，响应内容：{response_text[:200]}...")
        
        except Exception as e:
            print(f"第{retry+1}次调用LLM失败：{str(e)}")
    
    # 多次重试失败返回默认值
    return ("无法识别", "0.0", "解析失败；多次调用失败；特征无法提取")

# ========== 文件处理主函数 ==========
def process_query_classification(input_excel: str, output_excel: str):
    """
    批量处理excel文件中的Query分类
    参数：
        input_excel: 输入xlsx路径（必须包含query列）
        output_excel: 输出xlsx路径（添加类别、置信度、判断理由列）
    """
    try:
        # 读取输入文件
        df = pd.read_excel(input_excel)
        
        # 检查必要列
        if 'query' not in df.columns:
            raise ValueError("输入文件必须包含'query'列")
        
        # 封装单条 query 分类（便于并行）
        def _classify_query(q):
            if pd.isna(q):
                return ("无法识别", "0.0", "标题为空；无有效查询内容")
            return classify_single_query(str(q).strip())

        queries = df["query"].tolist()

        # 使用线程池并行处理，最多同时处理 5 条
        with ThreadPoolExecutor(max_workers=5) as executor:
            classify_results = list(
                tqdm(
                    executor.map(_classify_query, queries),
                    total=len(queries),
                    desc="分类进度（并行）",
                )
            )

        # 将结果写回 DataFrame（保持原顺序）
        categories, confidences, features = zip(*classify_results) if classify_results else ([], [], [])
        df["能力类别"] = categories
        df["能力类别置信度"] = confidences
        df["能力类别判断理由"] = features

        # 保存结果
        df.to_excel(output_excel, index=False)
        print(f"\n处理完成！结果已保存至：{output_excel}")
        print(f"总计处理 {len(df)} 条Query")
        
        # 输出分类统计
        print("\n分类统计：")
        category_counts = df['能力类别'].value_counts()
        for cat, count in category_counts.items():
            print(f"  {cat}: {count}条 ({count/len(df)*100:.1f}%)")
    
    except Exception as e:
        print(f"处理文件失败：{str(e)}")
        raise

